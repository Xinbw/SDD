"""Derive common-utility budget comparisons from the frozen three-seed means."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def read_mnist():
    result = {}
    active = None
    for line in (ROOT / 'results/SSD_COMPARISON.md').read_text().splitlines():
        heading = re.match(r'## (CIFAR-10|MNIST), α=(0\.1|1\.0)', line)
        if heading:
            active = float(heading[2]) if heading[1] == 'MNIST' else None
            if active is not None:
                result[active] = {'SDD': [], 'DP-FedCT': []}
        if active is None or not line.startswith('|'):
            continue
        cols = [s.strip().replace('**', '') for s in line.strip('|').split('|')]
        if not cols or not re.fullmatch(r'0?\.\d+|1\.0', cols[0]):
            continue
        eps = float(cols[0])
        for name, index in [('SDD', 2), ('DP-FedCT', 3)]:
            mean, std = map(float, cols[index].split('±'))
            result[active][name].append((eps, mean, std))
    assert all(len(v) == 7 for row in result.values() for v in row.values())
    return result


def budget_rows():
    data = read_mnist()
    rows = []
    for alpha, target in [(0.1, 0.85), (0.1, 0.90), (1.0, 0.90), (1.0, 0.95)]:
        chosen = {name: next(row for row in series if row[1] >= target)
                  for name, series in data[alpha].items()}
        sdd_eps = chosen['SDD'][0]
        fedct_eps = chosen['DP-FedCT'][0]
        rows.append((alpha, target, sdd_eps, fedct_eps, fedct_eps / sdd_eps))
    return rows


def main():
    lines = [r'% generated by export_budget_targets.py -- do not edit',
             r'\begin{table}[t]',
             r'  \caption{Privacy budgets needed for common MNIST utility targets. '
             r'Each entry is the first tested $\varepsilon$ whose three-seed mean '
             r'reaches the target. The complete budget grid and seed variation '
             r'are in Figure~\ref{fig:main-results}.}',
             r'  \label{tab:budget-targets}', r'  \small',
             r'  \begin{tabular}{@{}crrrr@{}}', r'    \toprule',
             r'    $\alpha$ & target & SDD $\varepsilon$ & DP-FedCT $\varepsilon$ & ratio \\',
             r'    \midrule']
    for alpha, target, sdd_eps, fedct_eps, ratio in budget_rows():
        lines.append(f'    {alpha:g} & {target * 100:.0f}\\% & {sdd_eps:g} & '
                     f'{fedct_eps:g} & ${ratio:g}\\times$ \\\\')
    lines += [r'    \bottomrule', r'  \end{tabular}', r'  \vspace{2pt}',
              r'  \parbox{\linewidth}{\footnotesize Ratios are DP-FedCT budget '
              r'divided by SDD budget on the measured grid. $\delta=10^{-5}$, '
              r'$T=3$, $t=0$. Utility evaluation estimates consensus from 100 '
              r'trained clients, with residual noise calibrated to $n=10^4$.}',
              r'\end{table}', '']
    path = ROOT / 'paper/tab-budget-targets.tex'
    path.write_text('\n'.join(lines))
    print('wrote', path)
    print('budget rows:', budget_rows())


if __name__ == '__main__':
    main()
