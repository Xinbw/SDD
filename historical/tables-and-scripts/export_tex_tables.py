def mia_table():
    import json
    L = ["% generated by export_tex_tables.py -- do not edit",
         "\\begin{table}[t]",
         "  \\caption{" + METADATA["tab-mia.tex"]["caption"] + "}",
         "  \\label{tab:mia}", "  \\small",
         "  \\begin{tabular}{@{}lrrrrr@{}}", "    \\toprule",
         "    $\\varepsilon$ & $d_{\\max}/\\Delta_2$ & $\\mu$ & AUC & "
         "TPR@1\\%FPR & $\\varepsilon_{\\mathrm{GDP}}$ \\\\", "    \\midrule"]
    audit_dir = Path("logs/dp_v2/mia_agg")
    if not audit_dir.is_dir():
        audit_dir = Path(__file__).resolve().parent.parent / "audit-inputs"
    for title, ds, a, kmap in (("CIFAR-10, $\\alpha=0.1$", "cifar10", 0.1, CIFAR_K),
                               ("MNIST, $\\alpha=1.0$", "mnist", 1.0, MNIST_A1_K)):
        L.append(f"    \\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\")
        for e in EPS:
            audit_path = audit_dir / f"mia_agg_{ds}_a{a}_K{kmap[e]}_s42.json"
            j = json.loads(audit_path.read_text())
            r = next((x for x in j["rows"] if f"{x['epsilon']:g}" == f"{float(e):g}"), None)
            if r is None:
                raise ValueError(f"Missing epsilon={e} in {audit_path}")
            dm = j["distance"]["max"] / j["distance"]["bound"]
            L.append(f"    \\quad {float(e):g} & {dm:.3f} & {r['mu_max']:.4f} & "
                     f"{r['auc_max']:.4f} & {r['tpr@0.01_max']:.4f} & "
                     f"{r['eps_gdp_max']:.3f} \\\\")
    L += ["    \\bottomrule", "  \\end{tabular}",
          "  \\vspace{2pt}",
          "  \\parbox{\\linewidth}{\\footnotesize " + METADATA["tab-mia.tex"]["note"] + "}",
          "\\end{table}", ""]
    write_table("tab-mia.tex", L)
    print(f"wrote {OUT}/tab-mia.tex")


