# --------------------------------------------------------- ablation + macros
# Everything below reads logs/dp_v2/ablation_current (run_ablation_current_config.sh),
# which re-runs each ablation axis in the current main-line configuration, plus the
# frozen main-line cells it is measured against. Rows whose runs have not landed
# yet are emitted as "--" rather than silently dropped.

ABL = "logs/dp_v2/ablation_current"


def _one(path):
    hits = glob.glob(path)
    return read(hits[0]) if hits else None


def _ref(e):
    """The main-line cell at CIFAR alpha=0.1, K=10, seed 42, given eps."""
    return first(cifar_ssd(e, 10, 42))


def _fmt(v, ref=None, direction=1):
    if v is None:
        return "--", "--"
    d = "" if ref is None else f"{direction * (v - ref) * 100:+.2f}"
    return f"{v:.4f}", d


def ablation_table():
    e1, e01 = "1.0", "0.1"
    r1, r01 = _ref(e1), _ref(e01)
    rows = []

    # Loss and coverage report the retained design's gain over each alternative.
    # Encoding and K retain alternative-minus-reference differences.
    rows.append(("\\emph{hard CE gain over soft KL}", None, None, -1))
    for lab, e, ref in (("$\\varepsilon=1$", e1, r1), ("$\\varepsilon=0.1$", e01, r01)):
        tag = e.replace(".", "_")
        rows.append((f"\\quad soft KL, {lab}", _one(f"{ABL}/softkl_eps{tag}.log"), ref, -1))

    t04 = _one(f"{ABL}/thr0_4_eps1_0.log")
    t06 = _one(f"{ABL}/thr0_6_eps1_0.log")
    same = (t04 is not None and t06 is not None and abs(t04 - t06) < 1e-9)
    rows.append(("\\emph{full coverage gain over filtering} ($\\varepsilon=1$)",
                 None, None, -1))
    rows.append(("\\quad threshold 0.25", _one(f"{ABL}/thr0_25_eps1_0.log"), r1, -1))
    rows.append((("\\quad thresholds 0.4 and 0.6" if same else "\\quad threshold 0.4"), t04, r1, -1))
    if not same:
        rows.append(("\\quad threshold 0.6", t06, r1, -1))

    rows.append(("\\emph{mean-posterior encoding}: change from vote", None, None, 1))
    for lab, e, ref in (("$\\varepsilon=1$", e1, r1), ("$\\varepsilon=0.1$", e01, r01)):
        tag = e.replace(".", "_")
        rows.append((f"\\quad {lab}", _one(f"{ABL}/encsoft_eps{tag}.log"), ref, 1))

    rows.append(("\\emph{granularity}: change from $K=10$ ($\\varepsilon=1$)",
                 None, None, 1))
    for K in (5, 20, 50, 100):
        rows.append((f"\\quad $K={K}$", _one(f"{ABL}/K{K}_eps1_0.log"), r1, 1))

    L = ["% generated by export_tex_tables.py -- do not edit",
         "\\begin{table}[t]",
         "  \\caption{Design diagnostics on CIFAR-10, $\\alpha=0.1$, $T=3$, "
         "seed 42. Loss and coverage isolate consensus extraction; encoding "
         "and granularity test the bounded release interface.}",
         "  \\label{tab:ablation}", "  \\small",
         "  \\begin{tabular}{@{}lrr@{}}", "    \\toprule",
         "    variant & accuracy & difference (pp) \\\\", "    \\midrule"]
    for lab, v, ref, direction in rows:
        if v is None and ref is None:
            L.append(f"    \\multicolumn{{3}}{{@{{}}l}}{{{lab}}} \\\\")
            continue
        a, d = _fmt(v, ref, direction)
        L.append(f"    {lab} & {a} & {d} \\\\")
    L += ["    \\bottomrule", "  \\end{tabular}",
          "  \\vspace{2pt}",
          "  \\parbox{\\linewidth}{\\footnotesize The main line scores "
          + (f"{r1:.4f}" if r1 is not None else "--")
          + " at $\\varepsilon=1$ and "
          + (f"{r01:.4f}" if r01 is not None else "--")
          + " at $\\varepsilon=0.1$. Accuracy is for the listed variant. Loss and "
          "coverage give reference minus variant; encoding and granularity give "
          "variant minus reference. All rows use one seed and $n=10^4$ noise "
          "calibration. Fixed-$K$ choices preserve sensitivity; varying $K$ changes it.}",
          "\\end{table}", ""]
    write_table("tab-ablation.tex", L)
    print(f"wrote {OUT}/tab-ablation.tex")


def cohort_table():
    """The scale characterisation: accuracy and pseudo-label accuracy vs cohort."""
    PL = re.compile(r"\[Proxy labels\] label_accuracy=([\d.]+)")

    def plabel(path):
        hits = glob.glob(path)
        if not hits:
            return None
        v = PL.findall(open(hits[0], errors="ignore").read())
        return float(v[-1]) if v else None

    L = ["% generated by export_tex_tables.py -- do not edit",
         "\\begin{table}[t]",
         "  \\caption{Cohort size against utility at $\\varepsilon=1$ "
         "(CIFAR-10, $\\alpha=0.1$, $K=10$, seed 42). The residual noise is "
         "$\\sigma/n$, so the pseudo-label channel only opens once it falls below "
         "the aggregate's cluster margin; Eq.~\\eqref{eq:scale} puts that crossing "
         "near $n\\approx\\CohortFloor{}$.}",
         "  \\label{tab:cohort}", "  \\small",
         "  \\begin{tabular}{@{}rrrr@{}}", "    \\toprule",
         "    cohort $n$ & residual noise $\\sigma/n$ & pseudo-label acc. & "
         "final acc. \\\\", "    \\midrule"]
    cfg = DPConfig(epsilon=1.0, delta=1e-5, q=1.0, num_clusters=10,
                   num_rounds=3, cohort_size=10000)
    for n in (100, 300, 1000, 3000, 10000):
        path = (f"{ABL}/cohort{n}_eps1_0.log" if n != 10000
                else "logs/dp_v2/k_eps_grid/ours_K10_eps1_0_s42.log")
        v, pl = _one(path), plabel(path)
        res = cfg.sigma_aggregate / n
        L.append(f"    {n} & {res:.4f} & "
                 f"{'--' if pl is None else f'{pl:.4f}'} & "
                 f"{'--' if v is None else f'{v:.4f}'} \\\\")
    L += ["    \\bottomrule", "  \\end{tabular}",
          "  \\vspace{2pt}",
          "  \\parbox{\\linewidth}{\\footnotesize Pseudo-label accuracy is that of "
          "the broadcast aggregate in the last round; $0.10$ is chance for ten "
          "classes. All rows spend the same $\\varepsilon=1$: the cohort changes what "
          "survives averaging, not the budget.}",
          "\\end{table}", ""]
    write_table("tab-cohort.tex", L)
    print(f"wrote {OUT}/tab-cohort.tex")


def _margin_k10():
    """Median margin of the one-hot vote aggregate; standard even-K median."""
    snapshot = Path(__file__).resolve().parents[1] / "validation-experiments/fixed_report_replay.json"
    return json.loads(snapshot.read_text())["margin_summary"]["vote_median"]


def macros():
    """Inline numbers used in prose, so they cannot drift from the logs."""
    e1 = "1.0"
    r1 = _ref(e1)
    enc = _one(f"{ABL}/encsoft_eps1_0.log")
    z = DPConfig(epsilon=1.0, delta=1e-5, q=1.0, num_clusters=20, num_rounds=3,
                 accounting="zcdp").sigma_aggregate
    r = DPConfig(epsilon=1.0, delta=1e-5, q=1.0, num_clusters=20, num_rounds=3,
                 accounting="rdp").sigma_aggregate
    # cohort floor at the MAIN-LINE configuration (K=10), not the K=20 figure the
    # earlier draft carried: sigma scales as sqrt(K) and the margin is wider at
    # K=10, so both factors move the floor down. Corroborated by tab-cohort.
    mk = _margin_k10()
    sig10 = DPConfig(epsilon=1.0, delta=1e-5, q=1.0, num_clusters=10, num_rounds=3,
                     accounting="zcdp").sigma_aggregate
    n_floor = None if mk is None else sig10 / mk
    defs = {
        "EncDeltaOne": "--" if (enc is None or r1 is None) else f"{(enc - r1) * 100:+.1f}",
        "SigmaZcdp": f"{z:.2f}",
        "SigmaRdp": f"{r:.2f}",
        "RdpSaving": f"{(1 - r / z) * 100:.1f}",
        "SigmaKTen": f"{sig10:.2f}",
        "MarginKTen": "--" if mk is None else f"{mk:.4f}",
        "CohortFloor": "--" if n_floor is None else f"{round(n_floor, -1):.0f}",
    }
    L = ["% generated by export_tex_tables.py -- do not edit",
         "% Inline numbers for the prose. Regenerate, do not retype."]
    L += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in defs.items()]
    open(f"{OUT}/numbers.tex", "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}/numbers.tex  {defs}")

if __name__ == "__main__":
    main()
