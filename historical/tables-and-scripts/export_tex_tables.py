"""Emit the paper's LaTeX tables from the logs -- no hand-copied numbers.

Writes into paper/:
    tab-main-a01.tex   accuracy, alpha=0.1  (CIFAR-10 | MNIST), 7 eps x 3 seeds
    tab-main-a10.tex   accuracy, alpha=1.0  (CIFAR-10 | MNIST)
    tab-fedavg.tex     DP-FedAvg baseline + the noise/signal ratio that explains it
    tab-ablation.tex   one design choice at a time, against the main-line cell
    numbers.tex        inline prose numbers as \newcommand macros
    tab-mia.tex        aggregate-level MIA: the tight case and the loose case

Paired t-tests are computed here (SDD vs each baseline, over the seeds both have)
so significance marks in the paper cannot drift from the logs. Run after any new
run lands, then recompile the paper.
"""

import glob
import json
from pathlib import Path
import math
import re
import statistics as st

from scipy import stats

from dp_utils import DPConfig
from export_comparison import (CIFAR_A1_K, CIFAR_K, EPS, MNIST_A1_K, MNIST_K,
                               a1_dir, cifar_fedct, cifar_pate, cifar_ssd,
                               mnist_fedct, mnist_pate, mnist_ssd, read)

SEEDS = (42, 43, 44)
OUT = "paper"
D_RESNET = 11_183_562
CLIP = 56.0
COHORT = 10000


METADATA = json.loads((Path(__file__).resolve().parent / "table_metadata.json").read_text())


def write_table(path, lines):
    """Apply editorial metadata without changing generated numerical rows."""
    entry = METADATA.get(path, {})
    for index, line in enumerate(lines):
        if line.startswith("  \\caption{") and "caption" in entry:
            lines[index] = "  \\caption{" + entry["caption"] + "}"
        if line.startswith("  \\parbox{\\linewidth}") and "note" in entry:
            lines[index] = "  \\parbox{\\linewidth}{\\footnotesize " + entry["note"] + "}"
    (Path(OUT) / path).write_text("\n".join(lines))


def first(patterns):
    for p in patterns:
        for h in sorted(glob.glob(p)):
            v = read(h)
            if v is not None:
                return v
    return None


def series(e, K, fn):
    """Per-seed accuracies, aligned by seed index (None where a run is missing)."""
    return [first(fn(e, K, s)) for s in SEEDS]


def paired(a, b):
    """(mean difference in points, p-value) over the seeds both methods have."""
    pairs = [(x, y) for x, y in zip(a, b) if x is not None and y is not None]
    if len(pairs) < 2:
        return None, None
    d = [(x - y) * 100 for x, y in pairs]
    if max(d) - min(d) < 1e-12:            # identical runs: t-test undefined
        return st.mean(d), 1.0 if abs(st.mean(d)) < 1e-12 else 0.0
    t, p = stats.ttest_rel([x for x, _ in pairs], [y for _, y in pairs])
    return st.mean(d), float(p)


def cell(v, bold=False, mark=""):
    got = [x for x in v if x is not None]
    if not got:
        return "--"
    s = f"{st.mean(got):.3f}" if len(got) == 1 else \
        f"{st.mean(got):.3f}\\,$\\pm$\\,{st.stdev(got):.3f}"
    if bold:
        s = f"\\textbf{{{s}}}"
    return s + mark


def sig(p):
    """Significance mark for a paired test at n=3."""
    if p is None:
        return ""
    if p < 0.01:
        return "$^{**}$"
    if p < 0.05:
        return "$^{*}$"
    return ""


# ------------------------------------------------------------------ main tables
def main_table(path, caption, label, combos):
    """One float, two dataset blocks side by side: eps | K, SDD, FedCT, PATE (x2)."""
    L = [f"% generated by export_tex_tables.py -- do not edit",
         "\\begin{table*}[t]", f"  \\caption{{{caption}}}", f"  \\label{{{label}}}",
         "  \\small",
         "  \\begin{tabular}{@{}l" + "rrrr" * len(combos) + "@{}}", "    \\toprule"]
    head1 = "    " + " & ".join(
        [""] + [f"\\multicolumn{{4}}{{c}}{{{name}}}" for name, _, _ in combos]) + " \\\\"
    rules = "    " + " ".join(
        f"\\cmidrule(l{{2pt}}r{{2pt}}){{{2 + 4 * i}-{5 + 4 * i}}}" for i in range(len(combos)))
    head2 = "    " + " & ".join(
        ["$\\varepsilon$"] + ["$K$ & SDD & DP-FedCT & PATE-DI"] * len(combos)) + " \\\\"
    L += [head1, rules, head2, "    \\midrule"]
    for e in EPS:
        row = [f"{float(e):g}"]
        for _, kmap, fns in combos:
            K = kmap[e]
            s = series(e, K, fns[0])
            f_ = series(e, K, fns[1])
            p_ = series(e, K, fns[2])
            _, pf = paired(s, f_)
            _, pp = paired(s, p_)
            win = all(x is not None for x in s) and \
                st.mean([x for x in s if x is not None]) >= max(
                    st.mean([x for x in v if x is not None] or [0]) for v in (f_, p_))
            row += [str(K), cell(s, bold=win), cell(f_, mark=sig(pf)), cell(p_, mark=sig(pp))]
        L.append("    " + " & ".join(row) + " \\\\")
    L += ["    \\bottomrule", "  \\end{tabular}",
          "  \\vspace{2pt}",
          "  \\parbox{\\linewidth}{\\footnotesize Mean client accuracy over 3 seeds "
          "(42/43/44), mean\\,$\\pm$\\,std across seeds. Bold marks the best mean. "
          "Marks on a baseline give the paired $t$-test of SDD against \\emph{that} "
          "baseline over the same seeds: $^{*}p<0.05$, $^{**}p<0.01$. $K$ is the "
          "cluster count used in that row (chosen per $\\varepsilon$ on seed 42; see "
          "\\S\\ref{sec:eval:setup}). $\\delta=10^{-5}$, $T=3$ rounds, cohort $10^4$ "
          "simulated, 100 clients, $t=0$.}",
          "\\end{table*}", ""]
    write_table(path, L)
    print(f"wrote {OUT}/{path}")


# ---------------------------------------------------------------- fedavg table
def noise_signal(eps, T):
    c = DPConfig(epsilon=eps, delta=1e-5, q=1.0, num_clusters=1,
                 num_rounds=T, cohort_size=COHORT)
    per_coord = c.sigma_aggregate * (2 * CLIP / math.sqrt(2)) / COHORT
    return per_coord * math.sqrt(D_RESNET) / CLIP


def fedavg_table():
    ACC = re.compile(r"Final mean accuracy: ([\d.]+)")

    def acc(p):
        hits = glob.glob(p)
        if not hits:
            return None
        m = ACC.search(open(hits[0], errors="ignore").read())
        return float(m.group(1)) if m else None

    def grp(tag, suffix=""):
        return [acc(f"logs/dp_v2/fedavg/fedavg_eps{tag}{suffix}_s{s}.log") for s in SEEDS]

    rows = [("0.01", "0_01"), ("0.1", "0_1"), ("1.0", "1_0"), ("4.0", "4_0"), ("10.0", "10_0")]
    L = ["% generated by export_tex_tables.py -- do not edit",
         "\\begin{table}[t]",
         "  \\caption{DP-FedAvg in the same trust model, accountant and data splits "
         "(CIFAR-10, $\\alpha=0.1$). The release is the clipped model update, "
         "$d=1.12\\times10^{7}$ coordinates, so the injected noise outweighs the "
         "signal by the ratio in the last column and no budget below "
         "$\\varepsilon\\approx8$ is usable.}",
         "  \\label{tab:fedavg}", "  \\small",
         "  \\begin{tabular}{@{}lrrr@{}}", "    \\toprule",
         "    $\\varepsilon$ & $T{=}3, E{=}20$ & $T{=}20, E{=}3$ & noise/signal \\\\",
         "    \\midrule"]
    for e, tag in rows:
        a, b = grp(tag), grp(tag, "_T20E3")
        L.append(f"    {float(e):g} & {cell(a)} & {cell(b)} & "
                 f"${noise_signal(float(e), 3):.1f}\\times$ \\\\")
    L += ["    \\bottomrule", "  \\end{tabular}",
          "  \\vspace{2pt}",
          "  \\parbox{\\linewidth}{\\footnotesize Random guessing is 0.10. The "
          "noise/signal column is "
          "$2\\sqrt{d}\\,\\sigma_{\\mathrm{agg}}/(\\sqrt2\\,n\\,C)$ at $T=3$, "
          "independent of the clipping norm $C$; $C=56$ is the median round-1 update "
          "norm of a pilot run used only to set $C$. Single-seed entries are the two "
          "budgets used "
          "only to locate the crossover.}",
          "\\end{table}", ""]
    write_table("tab-fedavg.tex", L)
    print(f"wrote {OUT}/tab-fedavg.tex")


